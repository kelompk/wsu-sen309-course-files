import unittest

from tests.helpers import temp_dir, fresh_db, capture, ingest, reconcile, one, query


class CleanTransfer(unittest.TestCase):
    def setUp(self):
        self.dir = temp_dir()
        self.db = fresh_db(self.dir)

    def test_every_reading_is_stored(self):
        code, out = ingest(self.db, capture(self.dir, count=60))
        self.assertEqual(code, 0, out)
        self.assertEqual(one(self.db, "SELECT COUNT(*) FROM reading"), 60)
        self.assertEqual(one(self.db, "SELECT status FROM ingest_run"), "DONE")

    def test_header_and_summary_are_recorded(self):
        ingest(self.db, capture(self.dir, count=10))
        row = query(self.db, "SELECT fw, period_ms, reported_count, reported_last_seq FROM boot_session")
        self.assertEqual(row, [("1.0", 1000, 10, 9)])

    def test_repeating_a_transfer_changes_nothing(self):
        f = capture(self.dir, count=30)
        ingest(self.db, f)
        code, out = ingest(self.db, f)
        self.assertEqual(one(self.db, "SELECT COUNT(*) FROM reading"), 30)
        self.assertEqual(one(self.db, "SELECT duplicates FROM ingest_run WHERE run_id = 2"), 30, out)

    def test_reconcile_agrees(self):
        ingest(self.db, capture(self.dir, count=60))
        code, out = reconcile(self.db)
        self.assertEqual(code, 0, out)
        self.assertIn("RECONCILED", out)


class FaultyTransfer(unittest.TestCase):
    """The standard faulty capture used in the workbook."""
    FAULTS = "corrupt@12,drop@25,dup@30,garbage@33,range@40,conflict@50"

    @classmethod
    def setUpClass(cls):
        cls.dir = temp_dir()
        cls.db = fresh_db(cls.dir)
        cls.code, cls.out = ingest(cls.db, capture(cls.dir, count=60, faults=cls.FAULTS))

    def test_counts(self):
        row = query(self.db, "SELECT inserted, duplicates, rejected FROM ingest_run")
        self.assertEqual(row, [(57, 1, 4)], self.out)

    def test_every_rejection_has_the_right_reason(self):
        reasons = [r[0] for r in query(self.db, "SELECT reason FROM rejected_line ORDER BY line_no")]
        self.assertEqual(reasons, ["CHECKSUM", "FORMAT", "RANGE", "CONFLICT"])

    def test_first_copy_wins_a_conflict(self):
        light = one(self.db, "SELECT light FROM reading WHERE seq = 45")
        self.assertEqual(light, 745)

    def test_reconcile_finds_the_gaps(self):
        code, out = reconcile(self.db)
        self.assertEqual(code, 1)
        self.assertIn("missing 3 [12, 25, 40]", out)

    def test_unknown_device_is_rejected(self):
        dir2 = temp_dir()
        db2 = fresh_db(dir2)
        ingest(db2, capture(dir2, count=5, device="SN99"))
        self.assertEqual(one(db2, "SELECT COUNT(*) FROM reading"), 0)
        self.assertEqual(one(db2, "SELECT COUNT(*) FROM rejected_line WHERE reason = 'UNKNOWN_DEVICE'"), 7)


if __name__ == "__main__":
    unittest.main()
