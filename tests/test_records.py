import os
import sys
import unittest

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
from host.records import parse_line, ParseError, Reading, Hello, EndOfRun, DeviceError  # noqa: E402
from fixture.protocol import frame  # noqa: E402


class GoodLines(unittest.TestCase):
    def test_reading_from_the_firmware(self):
        r = parse_line("R,SN01,1,8,6100,36.0,307,ALM*03\r\n")
        self.assertEqual(r, Reading("SN01", 1, 8, 6100, 36.0, 307, "ALM"))

    def test_hello(self):
        self.assertEqual(parse_line("H,SN01,1,1.0,1000*4B\r\n"), Hello("SN01", 1, "1.0", 1000))

    def test_end_of_run(self):
        self.assertEqual(parse_line("E,SN01,1,18,17*67\r\n"), EndOfRun("SN01", 1, 18, 17))

    def test_device_error(self):
        self.assertEqual(parse_line("X,SN01,1,SENSOR,A0*12\r\n"), DeviceError("SN01", 1, "SENSOR", "A0"))

    def test_negative_temperature(self):
        r = parse_line(frame("R,SN02,3,5,5000,-0.5,0,RUN") + "\n")
        self.assertEqual((r.temp_c, r.light), (-0.5, 0))

    def test_lower_case_checksum_is_accepted(self):
        self.assertIsInstance(parse_line("R,SN01,1,10,7100,36.0,307,ALM*3b"), Reading)

    def test_blank_line_is_ignored(self):
        self.assertIsNone(parse_line("\r\n"))


class BadLines(unittest.TestCase):
    def reason(self, text):
        with self.assertRaises(ParseError) as cm:
            parse_line(text)
        return cm.exception.reason

    def test_cut_line(self):
        self.assertEqual(self.reason("R,SN01,1,15,1500"), "TRUNCATED")

    def test_cut_inside_the_checksum(self):
        self.assertEqual(self.reason("R,SN01,1,8,6100,36.0,307,ALM*0"), "TRUNCATED")

    def test_one_character_changed(self):
        self.assertEqual(self.reason("R,SN01,1,8,6100,36.7,307,ALM*03"), "CHECKSUM")

    def test_noise(self):
        self.assertEqual(self.reason("~~ #@! line noise 0x7F ~~"), "FORMAT")

    def test_wrong_number_of_fields(self):
        self.assertEqual(self.reason(frame("R,SN01,1,8,6100,36.0,307")), "FORMAT")

    def test_field_not_a_number(self):
        self.assertEqual(self.reason(frame("R,SN01,1,8,6100,hot,307,RUN")), "FORMAT")

    def test_bad_device_id(self):
        self.assertEqual(self.reason(frame("R,XX1,1,8,6100,24.0,307,RUN")), "FORMAT")

    def test_temperature_too_high(self):
        self.assertEqual(self.reason(frame("R,SN01,1,40,40000,150.0,756,RUN")), "RANGE")

    def test_light_too_high(self):
        self.assertEqual(self.reason(frame("R,SN01,1,40,40000,24.0,1024,RUN")), "RANGE")

    def test_unknown_state(self):
        self.assertEqual(self.reason(frame("R,SN01,1,40,40000,24.0,500,OK")), "RANGE")

    def test_period_out_of_range(self):
        self.assertEqual(self.reason(frame("H,SN01,1,1.0,50")), "RANGE")


class FirmwareContract(unittest.TestCase):
    """Every line the reference firmware printed in the simulator must parse without error."""

    def test_recorded_firmware_output(self):
        path = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "data", "firmware_sample.txt")
        n = 0
        with open(path, newline="") as f:
            for line in f:
                if parse_line(line) is not None:
                    n += 1
        self.assertGreater(n, 20)


if __name__ == "__main__":
    unittest.main()
